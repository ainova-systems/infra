import { stringify } from 'yaml';
import { connection, declaredValues, type EnvFile } from './env.ts';
import { qualifyRole, type Host, type Project } from './manifest.ts';

/**
 * Everything Ansible needs that is the same in every project is generated here, per run, from the manifest:
 * the inventory (classes and groups, connection values from the operator env), ansible.cfg, and the apply and
 * check playbooks of one host. A project keeps only its variables, its own roles and its own playbooks.
 */
export interface Bundle {
  /** File name -> content, written into the run directory. */
  files: Map<string, string>;
}

export interface GenerateOptions {
  /** The project root as the Linux side sees it (infra_project_root). */
  linuxRoot: string;
  /** The project's Ansible directory as the Linux side sees it. */
  linuxAnsibleDir: string;
}

const HEADER = '# Generated by the infra CLI for one run; never edited or committed.\n';

function yaml(value: unknown): string {
  return HEADER + stringify(value, { lineWidth: 0 });
}

export function inventory(project: Project, env: EnvFile, options: GenerateOptions): string {
  const children: Record<string, { hosts: Record<string, Record<string, unknown>> }> = {};
  const add = (group: string, id: string, vars: Record<string, unknown>) => {
    children[group] ??= { hosts: {} };
    children[group].hosts[id] = vars;
  };
  for (const host of project.manifest.hosts) {
    const reach = connection(env, host);
    const vars: Record<string, unknown> = {
      host_status: host.status,
      infra_class: host.class,
      ansible_port: reach.port,
      // The admin the env file names, else the admin the project's variables declare.
      ansible_user: reach.admin ?? '{{ host_base_admin_user }}',
    };
    if (host.provider) vars.infra_provider = host.provider;
    if (reach.address) vars.ansible_host = reach.address;
    add(host.class, host.id, vars);
    for (const group of host.groups) add(group, host.id, {});
  }
  return yaml({
    all: {
      vars: {
        infra_project: project.manifest.project,
        infra_project_root: options.linuxRoot,
        infra_env: declaredValues(project, env),
      },
      children,
    },
  });
}

export function ansibleConfig(options: GenerateOptions): string {
  return [
    HEADER.trimEnd(),
    '[defaults]',
    'inventory = inventory.yml',
    `roles_path = ${options.linuxAnsibleDir}/roles`,
    'host_key_checking = True',
    'retry_files_enabled = False',
    'interpreter_python = auto_silent',
    'any_errors_fatal = True',
    'forks = 5',
    '',
    '[ssh_connection]',
    'pipelining = True',
    'ssh_args = -o StrictHostKeyChecking=yes -o UpdateHostKeys=no -o ControlMaster=auto -o ControlPersist=60s',
    '',
  ].join('\n');
}

function hookTask(project: Project, hook: Host['before'][number]): Record<string, unknown> {
  return {
    name: `${hook.role} ${hook.tasksFrom}`,
    'ansible.builtin.include_role': { name: qualifyRole(project, hook.role), tasks_from: hook.tasksFrom },
    tags: hook.tags,
  };
}

/** The apply playbook of one host: the guards, then its roles in manifest order, each tagged with its name. */
export function sitePlaybook(project: Project, host: Host): string {
  const plays: Record<string, unknown>[] = [
    {
      name: 'Refuse a host that is not ready for an apply',
      hosts: host.id,
      gather_facts: false,
      tags: ['always'],
      tasks: [
        {
          name: 'Host is planned or active, addressed, and active unless this is its first apply',
          'ansible.builtin.assert': {
            that: [
              "host_status in ['planned', 'active']",
              "host_status == 'active' or (infra_first_apply | default(false) | bool)",
              "ansible_host | default('') | length > 0",
            ],
            fail_msg:
              "{{ inventory_hostname }} is {{ host_status }}: a planned host needs 'infra apply --first-apply', and every host an address in the operator env file",
            quiet: true,
          },
        },
      ],
    },
    {
      // Remote access and the firewall are never applied from the machine they would lock out.
      name: 'Never apply host_base to the control node itself',
      hosts: host.id,
      gather_facts: false,
      tags: ['host_base'],
      tasks: [
        {
          name: 'Read the target machine id',
          'ansible.builtin.command': 'cat /etc/machine-id',
          register: 'infra_target_machine_id',
          changed_when: false,
          check_mode: false,
        },
        {
          name: 'Target is not the machine running Ansible',
          'ansible.builtin.assert': {
            that: [
              "lookup('ansible.builtin.env', 'INFRA_CONTROL_MACHINE_ID') | length > 0",
              "infra_target_machine_id.stdout | trim != lookup('ansible.builtin.env', 'INFRA_CONTROL_MACHINE_ID') | trim",
            ],
            fail_msg: '{{ inventory_hostname }} is the control node; apply host_base from an operator workstation',
            quiet: true,
          },
        },
      ],
    },
  ];
  const apply: Record<string, unknown> = {
    name: `Apply ${host.id}`,
    hosts: host.id,
    become: true,
  };
  if (host.before.length > 0) apply.pre_tasks = host.before.map((hook) => hookTask(project, hook));
  apply.roles = host.roles.map((role) => ({ role: qualifyRole(project, role), tags: [role.split('.').at(-1)!] }));
  if (host.after.length > 0) apply.post_tasks = host.after.map((hook) => hookTask(project, hook));
  plays.push(apply);
  return yaml(plays);
}

/** The read-only check of one host: host_health, then every role's check, all failures in one report. */
export function checkPlaybook(project: Project, host: Host, only: string[] = []): string {
  const roles = ['ainova.infra.host_health', ...host.roles.map((role) => qualifyRole(project, role))];
  const unique = [...new Set(roles)];
  const vars: Record<string, unknown> = { role_checks_roles: unique };
  if (only.length > 0) vars.role_checks_only = only.map((role) => qualifyRole(project, role));
  return yaml([
    {
      name: `Check ${host.id}`,
      hosts: host.id,
      become: true,
      gather_facts: true,
      roles: [{ role: 'ainova.infra.role_checks', vars }],
    },
  ]);
}

export function bundle(project: Project, env: EnvFile, options: GenerateOptions, hosts: Host[], extra: Map<string, string> = new Map()): Bundle {
  const files = new Map<string, string>([
    ['ansible.cfg', ansibleConfig(options)],
    ['inventory.yml', inventory(project, env, options)],
  ]);
  for (const host of hosts) {
    files.set(`site-${host.id}.yml`, sitePlaybook(project, host));
    files.set(`check-${host.id}.yml`, checkPlaybook(project, host));
  }
  for (const [name, content] of extra) files.set(name, content);
  return { files };
}
